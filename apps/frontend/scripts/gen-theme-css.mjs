/**
 * Generate default.css (tema statis: light + dark, seed default).
 * Build: esbuild bundle → node. Role list dibaca dari roles.ts — sinkron runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  Hct,
  Variant,
  DynamicScheme,
  MaterialDynamicColors,
  hexFromArgb,
  argbFromHex,
} from "@material/material-color-utilities";

// Root = direktori kerja (wajib jalankan dari apps/frontend)
const root = path.resolve(process.cwd());

const rolesSrc = readFileSync(
  path.join(root, "src/design-system/themes/roles.ts"),
  "utf8",
);
const roles = [...rolesSrc.matchAll(/^  "([a-zA-Z]+)",$/gm)].map((m) => m[1]);
if (roles.length < 30) throw new Error("role list gagal diparse: " + roles.length);

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
// SPACEX UNIFIED — hitam pekat (1 tema dengan login spacex.com)
const seed = argbFromHex("#000000");
const accessors = new MaterialDynamicColors();

function block(isDark) {
  const scheme = new DynamicScheme({
    sourceColorHct: Hct.fromInt(seed),
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
  });
  return roles
    .map((r) => `  --vm3-color-${kebab(r)}: ${hexFromArgb(accessors[r]().getArgb(scheme))};`)
    .join("\n");
}

const css = `/* GENERATED by scripts/gen-theme-css.mjs — jangan edit manual.
   Regenerate: node scripts/gen-theme-css.mjs (via esbuild bundle) */
@layer vm3-theme {
  :root {
${block(false)}
  }

  [data-theme="dark"] {
${block(true)}
  }
}
`;

writeFileSync(path.join(root, "src/design-system/themes/default.css"), css);
console.log("default.css regenerated:", roles.length, "roles");
